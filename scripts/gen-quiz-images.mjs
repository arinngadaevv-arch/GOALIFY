import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Records which quiz answer photos actually exist in public/quiz, so the UI
 * can render the illustrated fallback without first firing a request that
 * 404s. Runs before dev and build — drop a PNG in and it is picked up on the
 * next start.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const photoDir = join(root, "public", "quiz");
const outFile = join(root, "src", "lib", "goalify", "quiz-images.generated.ts");

const files = existsSync(photoDir)
  ? readdirSync(photoDir).filter((name) => /\.(png|jpg|jpeg|webp|avif)$/i.test(name))
  : [];

const paths = files.map((name) => `/quiz/${name}`).sort();

const body = `// GENERATED by scripts/gen-quiz-images.mjs — do not edit by hand.
// Rerun with \`npm run gen:quiz-images\` (also runs before dev and build).

export const AVAILABLE_QUIZ_IMAGES: ReadonlySet<string> = new Set([
${paths.map((p) => `  ${JSON.stringify(p)},`).join("\n")}
]);
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
console.log(`gen-quiz-images: ${paths.length} photo(s) found`);
